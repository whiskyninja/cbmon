def merge(arr):
    out = []
    for row in arr:
        code = row[0]
        state = status_by_code.get(code, "clear")
        out.append(row + [state])
    return out

def to_js(arr, indent="    "):
    lines = []
    for row in arr:
        code, name, gap, conv, maturity, state = row
        lines.append(f'{indent}["{code}","{name}",{gap},{conv},"{maturity}","{state}"],')
    return "\n".join(lines)

